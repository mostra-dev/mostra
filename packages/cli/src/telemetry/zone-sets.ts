/** Names that are UTC, unknown or legacy European zones, asked first wherever they are. */
const ASK_FIRST_NAMES: readonly string[] = [
  "CET",
  "EET",
  "WET",
  "MET",
  "UTC",
  "GMT",
  "Universal",
  "Zulu",
  "Greenwich",
  "Factory",
];

/** The ask-first zones and every zone name tzdata knows. */
export interface ZoneSets {
  readonly version: string;
  readonly askFirst: readonly string[];
  readonly known: readonly string[];
}

/**
 * The `Link TARGET NAME` lines of a tzdata file, with the zone a `#= ZONE` comment names: the one
 * the alias meant before tzdata merged it (`Iceland` links to `Africa/Abidjan`, `#=
 * Atlantic/Reykjavik`).
 */
function links(text: string): { target: string; name: string; meant?: string }[] {
  const found: { target: string; name: string; meant?: string }[] = [];
  for (const line of text.split("\n")) {
    const fields = line.replace(/#.*/, "").trim().split(/\s+/);
    if (fields[0] !== "Link" || !fields[1] || !fields[2]) continue;
    const meant = /#=\s*(\S+)/.exec(line)?.[1];
    found.push({ target: fields[1], name: fields[2], ...(meant !== undefined ? { meant } : {}) });
  }
  return found;
}

/** The `Zone NAME …` names of a tzdata file. */
function zones(text: string): string[] {
  const found: string[] = [];
  for (const line of text.split("\n")) {
    const fields = line.replace(/#.*/, "").trim().split(/\s+/);
    if (fields[0] === "Zone" && fields[1]) found.push(fields[1]);
  }
  return found;
}

/** Builds the sets from the tzdata files' texts. */
export function buildZoneSets(files: {
  readonly version: string;
  readonly zoneTab: string;
  readonly backward: string;
  readonly etcetera: string;
  readonly factory: string;
}): ZoneSets {
  const countries = new Set(ASK_FIRST_COUNTRIES);
  const known = new Set<string>();
  const askFirst = new Set<string>(ASK_FIRST_NAMES);
  for (const line of files.zoneTab.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const [code, , name] = line.split("\t");
    if (!code || !name) continue;
    known.add(name);
    if (countries.has(code)) askFirst.add(name);
  }
  const etcetera = [...zones(files.etcetera), ...links(files.etcetera).map((link) => link.name)];
  for (const name of etcetera) {
    known.add(name);
    // UTC and its offsets: Etc/* is asked first, whatever its offset (D140 item 10).
    if (name.startsWith("Etc/") || name === "GMT") askFirst.add(name);
  }
  for (const name of zones(files.factory)) known.add(name);
  // Aliases of an ask-first name are ask-first; matched as given, never by their target.
  const backward = links(files.backward);
  let grew = true;
  while (grew) {
    grew = false;
    for (const { target, name, meant } of backward) {
      known.add(name);
      known.add(target);
      const asks = askFirst.has(target) || (meant !== undefined && askFirst.has(meant));
      if (asks && !askFirst.has(name)) {
        askFirst.add(name);
        grew = true;
      }
    }
  }
  for (const name of ASK_FIRST_NAMES) known.add(name);
  return {
    version: files.version.trim(),
    askFirst: [...askFirst].sort(),
    known: [...known].sort(),
  };
}

/** The generated module's text. */
export function zonesModule(sets: ZoneSets): string {
  const list = (names: readonly string[]): string =>
    names.map((name) => `  ${JSON.stringify(name)},`).join("\n");
  return `// Generated by scripts/ask-first-zones.ts from tzdata ${sets.version} (data/tzdata/). Don't edit.

/** The tzdata release the zones come from (VERIFIED_FACTS, WP-10). */
export const TZDATA_VERSION = ${JSON.stringify(sets.version)};

/** The time zones where Mostra asks before sending telemetry (D140 item 10), matched as given. */
export const ASK_FIRST_ZONES: readonly string[] = [
${list(sets.askFirst)}
];

/** Every zone name tzdata ${sets.version} knows; anything else is an unknown zone. */
export const KNOWN_ZONES: readonly string[] = [
${list(sets.known)}
];
`;
}
