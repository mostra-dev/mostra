/**
 * A theme as CSS: its faces as `@font-face` rules, and its colours, faces, radius and motion as
 * custom properties under shadcn's names, light by default, dark when the device prefers it, and
 * either one when the page's `<html data-appearance>` says so (a person's own switch).
 */
import { type Color, cssColor } from "./color.ts";
import type { Face, Palette, Stage, Theme } from "./theme.ts";

/** Where a stylesheet finds the faces' files. */
export interface StylesheetOptions {
  /**
   * The URL prefix the theme's font files are served under, ending in `/`, such as
   * `/_mostra/theme/`; each file keeps its package-relative path after it (`fonts/….woff2`).
   * Default `./`, beside the stylesheet in this package.
   */
  readonly assetBase?: string;
  /** Leave out the `@font-face` rules (a page that loads them elsewhere). */
  readonly faces?: boolean;
}

/** The custom property of a palette role: `cardForeground` is `--card-foreground`. */
export function variableOf(role: string): string {
  return `--${role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}`;
}

function paletteVariables(palette: Palette): string[] {
  const lines: string[] = [];
  for (const [role, value] of Object.entries(palette)) {
    if (role === "chart") {
      (value as readonly Color[]).forEach((color, index) => {
        lines.push(`--chart-${index + 1}: ${cssColor(color)};`);
      });
    } else lines.push(`${variableOf(role)}: ${cssColor(value as Color)};`);
  }
  return lines;
}

function stageVariables(stage: Stage | undefined): string[] {
  if (!stage) return [];
  return [
    `--stage: ${cssColor(stage.background)};`,
    `--stage-foreground: ${cssColor(stage.foreground)};`,
    ...stage.shapes.map((color, index) => `--stage-shape-${index + 1}: ${cssColor(color)};`),
  ];
}

function stack(face: Face): string {
  return `"${face.family}", ${face.fallback}`;
}

function fontFaces(theme: Theme, base: string): string[] {
  const seen = new Set<string>();
  const rules: string[] = [];
  for (const face of Object.values(theme.faces)) {
    for (const file of face.files) {
      if (seen.has(file.file)) continue;
      seen.add(file.file);
      rules.push(
        `@font-face {\n  font-family: "${face.family}";\n  font-style: ${file.style};\n  font-display: swap;\n  font-weight: ${file.weight};\n  src: url("${base}${file.file}") format("woff2");\n  unicode-range: ${file.unicodeRange};\n}`,
      );
    }
  }
  return rules;
}

const block = (selector: string, lines: readonly string[]): string =>
  `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}`;

/**
 * The stylesheet of a theme: its faces, then `:root`'s light values, the dark values under
 * `prefers-color-scheme: dark` unless the page chose light, and each mode under its
 * `data-appearance`. The text is deterministic: the same theme gives the same bytes.
 */
export function themeStylesheet(theme: Theme, options: StylesheetOptions = {}): string {
  const base = options.assetBase ?? "./";
  const shared = [
    `--font-sans: ${stack(theme.faces.sans)};`,
    `--font-display: ${stack(theme.faces.display)};`,
    `--font-mono: ${stack(theme.faces.mono)};`,
    `--radius: ${theme.radius};`,
    `--press-scale: ${theme.motion.pressScale};`,
    `--press-ms: ${theme.motion.pressMs}ms;`,
    `--state-ms: ${theme.motion.stateMs}ms;`,
  ];
  const light = [
    "color-scheme: light;",
    ...paletteVariables(theme.modes.light),
    ...stageVariables(theme.stage?.light),
  ];
  const dark = [
    "color-scheme: dark;",
    ...paletteVariables(theme.modes.dark),
    ...stageVariables(theme.stage?.dark),
  ];
  return [
    `/* ${theme.name} (${theme.id}), theme revision ${theme.revision}: generated by @mostra/themes. */`,
    ...(options.faces === false ? [] : fontFaces(theme, base)),
    block(":root", [...shared, ...light]),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-appearance="light"])', dark)
      .split("\n")
      .map((line) => `  ${line}`)
      .join("\n")}\n}`,
    block(':root[data-appearance="dark"]', dark),
    block(':root[data-appearance="light"]', light),
    "",
  ].join("\n");
}
