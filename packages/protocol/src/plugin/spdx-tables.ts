/**
 * Builds `spdx.generated.ts` from the SPDX License List's own data (`data/spdx/`, CC0-1.0):
 * every license ID with whether OSI approved it and whether the FSF calls it free, and every
 * exception ID. `scripts/spdx.ts` writes the module; a test checks it against the data.
 */

/** What the generated module holds. */
export interface SpdxTables {
  readonly version: string;
  /** Each license ID with its flags: `o` OSI-approved, `f` FSF libre, `d` deprecated. */
  readonly licenses: Readonly<Record<string, string>>;
  readonly exceptions: readonly string[];
}

/** The tables from the list's `licenses.json` and `exceptions.json`. */
export function spdxTables(licensesJson: string, exceptionsJson: string): SpdxTables {
  const licenses = JSON.parse(licensesJson) as {
    licenseListVersion: string;
    licenses: {
      licenseId: string;
      isOsiApproved?: boolean;
      isFsfLibre?: boolean;
      isDeprecatedLicenseId?: boolean;
    }[];
  };
  const exceptions = JSON.parse(exceptionsJson) as {
    licenseListVersion: string;
    exceptions: { licenseExceptionId: string }[];
  };
  if (licenses.licenseListVersion !== exceptions.licenseListVersion) {
    throw new Error(
      `licenses.json is ${licenses.licenseListVersion} and exceptions.json ${exceptions.licenseListVersion}.`,
    );
  }
  const table: Record<string, string> = {};
  for (const license of [...licenses.licenses].sort((a, b) =>
    a.licenseId < b.licenseId ? -1 : 1,
  )) {
    table[license.licenseId] =
      `${license.isOsiApproved ? "o" : ""}${license.isFsfLibre ? "f" : ""}${license.isDeprecatedLicenseId ? "d" : ""}`;
  }
  return {
    version: licenses.licenseListVersion,
    licenses: table,
    exceptions: exceptions.exceptions.map((exception) => exception.licenseExceptionId).sort(),
  };
}

/** A string array as Biome formats it: one element a line, with a trailing comma. */
function list(values: readonly string[]): string {
  return `[\n${values.map((value) => `  ${JSON.stringify(value)},\n`).join("")}]`;
}

/** The text of `spdx.generated.ts`. */
export function spdxModule(tables: SpdxTables): string {
  const licenses = Object.entries(tables.licenses).map(([id, flags]) => `${id}:${flags}`);
  return `/**
 * Generated by \`node packages/protocol/scripts/spdx.ts\` from the SPDX License List ${tables.version}
 * (\`data/spdx/\`, CC0-1.0). Don't edit: replace the data and run the script.
 */

/** The SPDX License List release these tables come from. */
export const SPDX_LICENSE_LIST_VERSION: string = ${JSON.stringify(tables.version)};

/**
 * Every license ID with its flags after a colon: \`o\` OSI-approved, \`f\` FSF libre, \`d\`
 * deprecated.
 */
export const SPDX_LICENSES: readonly string[] = ${list(licenses)};

/** Every license exception ID (the right side of \`WITH\`). */
export const SPDX_EXCEPTIONS: readonly string[] = ${list(tables.exceptions)};
`;
}
