const runtime = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(runtime, "../..");
// --only <requirement> replays its seeds; --name <text> narrows them to names containing it.
const { values } = parseArgs({
  options: {
    only: { type: "string" },
    name: { type: "string" },
    // Checks that every seed still finds what it plants into, and runs nothing: a seed whose
    // anchor moved is a proof that silently stopped proving (the boundaries job runs this).
    anchors: { type: "boolean", default: false },
  },
});

if (values.anchors) {
  const stale: string[] = [];
  const ambiguous: string[] = [];
  for (const seed of SEEDS) {
    for (const edit of [{ file: seed.file, from: seed.from }, ...(seed.also ?? [])]) {
      const path = join(runtime, edit.file);
      const text = existsSync(path) ? readFileSync(path, "utf8") : "";
      const count = text.split(edit.from).length - 1;
      const where = `${seed.requirement} | ${seed.name} (${edit.file})`;
      if (count === 0) stale.push(where);
      // Planted at the first match, which still proves something, but which one is luck.
      else if (count > 1) ambiguous.push(`${where}: ${count} matches`);
    }
  }
  for (const line of ambiguous) console.log(`  ! ${line}`);
  if (stale.length > 0) {
    console.error(`✗ seed anchors: ${stale.length} of ${SEEDS.length} seeds can't be planted`);
    for (const line of stale) console.error(`  - ${line}`);
    process.exit(1);
  }
  console.log(
    `✓ seed anchors: all ${SEEDS.length} seeds can be planted${ambiguous.length > 0 ? ` (${ambiguous.length} at the first of several matches)` : ""}`,
  );
  process.exit(0);
}

const WINDOWS_HOST = process.platform === "win32";

function build(seed?: Seed): void {
  // pnpm is a `.cmd` on Windows, which only a shell runs.
  const shell = WINDOWS_HOST;
  if (seed?.platform === "win32") {
    if (seed.file.includes("crates/mostra-win")) {
      // A seed that doesn't compile is a broken seed, not a caught one: say why. Windows' virus
      // scan holds a program it just saw written for a moment, and Cargo can't replace it then
      // ("Access is denied", seen in WP-W2's seed runs), so a failed build is tried twice more.
      for (let attempt = 1; ; attempt++) {
        try {
          execFileSync("cargo", ["build", "-p", "mostra-win", "--release", "--locked"], {
            cwd: root,
            stdio: ["ignore", "ignore", "inherit"],
          });
          break;
        } catch (error) {
          if (attempt === 3) throw error;
          Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 5000);
        }
      }
    }
    // The packages Windows runs so far (WP-W1, WP-W2).
    for (const name of [
      "@mostra/protocol",
      "@mostra/server",
      "@mostra/worker",
      "@mostra/react",
      "@mostra/shell",
      "@mostra/verify",
      "@mostra/runtime",
      "@mostra/sdk",
      "@mostra/cli",
    ]) {
      execFileSync("pnpm", ["--filter", name, "build"], { cwd: root, stdio: "ignore", shell });
    }
    return;
  }
  for (const name of [
    "@mostra/protocol",
    "@mostra/server",
    "@mostra/worker",
    "@mostra/react",
    "@mostra/shell",
    "@mostra/verify",
    "@mostra/runtime",
    "@mostra/sdk",
    "@mostra/cli",
    "create-mostra",
  ]) {
    execFileSync("pnpm", ["--filter", name, "build"], { cwd: root, stdio: "ignore", shell });
  }
}

/** An argument as cmd.exe passes it on when a shell runs the command (Windows only). */
function quoteForShell(argument: string): string {
  return WINDOWS_HOST && /[\s"'&|<>^]/.test(argument)
    ? `"${argument.replaceAll('"', '""')}"`
    : argument;
}

function check(seed: Seed): { ok: boolean; summary: string } {
  const result = seed.e2e
    ? spawnSync("npx", ["playwright", "test", ...seed.check], {
        cwd: join(root, "tests", "e2e"),
        encoding: "utf8",
      })
    : // Through pnpm, as `pnpm check` runs a suite: its `vitest` shim puts pnpm's hoisted
      // packages on NODE_PATH, which a supervisor started from a checkout needs to load
      // oxc-parser's native binding (found in WP-W2: VR-08's dev seeds came back red when vitest
      // ran without it). pnpm is a `.cmd` on Windows, which only a shell runs.
      spawnSync("pnpm", ["exec", "vitest", "run", ...seed.check.map(quoteForShell)], {
        cwd: join(runtime, seed.cwd ?? "."),
        encoding: "utf8",
        shell: WINDOWS_HOST,
      });
  const text = stripVTControlCharacters(`${result.stdout}${result.stderr}`);
  const summary =
    text
      .split("\n")
      .find((line) => line.includes("Tests ") || /^\s*\d+ (passed|failed)/.test(line)) ??
    "no summary";
  return { ok: result.status === 0, summary: summary.trim() };
}

let restore: (() => void) | undefined;
process.on("SIGINT", () => {
  restore?.();
  process.exit(130);
});

let missed = 0;
for (const seed of SEEDS) {
  if (values.only && seed.requirement !== values.only) continue;
  if (values.name && !seed.name.includes(values.name)) continue;
  if (
    seed.platform !== undefined &&
    (seed.platform === "posix" ? WINDOWS_HOST : seed.platform !== process.platform)
  ) {
    console.log(`${seed.requirement} | ${seed.name} | skipped: needs ${seed.platform}`);
    continue;
  }
  const edits = [{ file: seed.file, from: seed.from, to: seed.to }, ...(seed.also ?? [])];
  const originals = edits.map((edit) => {
    const path = join(runtime, edit.file);
    return { path, edit, text: readFileSync(path, "utf8") };
  });
  const absent = originals.find(({ edit, text }) => !text.includes(edit.from));
  if (absent) {
    console.log(`${seed.requirement} | ${seed.name} | SEED NOT FOUND in ${absent.edit.file}`);
    missed++;
    continue;
  }
  restore = () => {
    for (const { path, text } of originals) writeFileSync(path, text);
  };
  let red: { ok: boolean; summary: string };
  try {
    for (const { path, edit } of originals) {
      writeFileSync(path, readFileSync(path, "utf8").replace(edit.from, edit.to));
    }
    build(seed);
    red = check(seed);
  } finally {
    restore();
    restore = undefined;
  }
  build(seed);
  const green = check(seed);
  if (red.ok || !green.ok) missed++;
  console.log(
    `${seed.requirement} | ${seed.name} | seeded: ${red.ok ? "GREEN (missed)" : "red"} (${red.summary}) | restored: ${green.ok ? "green" : "RED"} (${green.summary})`,
  );
}
process.exit(missed === 0 ? 0 : 1);
